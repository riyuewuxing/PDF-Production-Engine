// @vitest-environment node
import {afterEach,describe,expect,it} from 'vitest';
import {promises as fs} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createHash,randomUUID} from 'node:crypto';
import {PdfReceiptVault,readPdfFingerprint,checkFingerprint,documentSha256,canCheckRecordedPdf,canCheckRecordedRealPdf,MAX_RECEIPT_PDF_BYTES} from './pdfReceipt';
import {LocalResumeStore} from '../src/server/localFsApi';
import {JobApplicationSchema} from '../src/schema/applicationSchema';
import {comparisonFixture} from '../src/lib/comparisonSyntheticFixture';
const roots:string[]=[];
const bytes=Buffer.from('%PDF-1.7\nsynthetic receipt fixture\n%%EOF\n');
async function fixture(){
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'synthetic-pdf-receipt-'));roots.push(root);
 const dir=path.join(root,'exports');await fs.mkdir(dir);
 const file=path.join(dir,'resume.pdf');await fs.writeFile(file,bytes);
 const doc=comparisonFixture(),vault=new PdfReceiptVault();
 const issued=await vault.issue(file,'synthetic',doc,bytes);
 const store=new LocalResumeStore(path.join(root,'data'));
 const entry=JobApplicationSchema.parse({id:randomUUID(),company:'合成学校',resumeSlug:'synthetic',exportedFilePath:file});
 return {root,dir,file,doc,vault,issued,store,entry};
}
afterEach(async()=>{await Promise.all(roots.splice(0).map(root=>fs.rm(root,{recursive:true,force:true})));});
describe('actual PDF byte fingerprint and export receipt',()=>{
 it('compares generated bytes with readback, and binds token to document, slug and exact path',async()=>{
  const {file,doc,vault,issued}=await fixture();const r=issued.pdfReceipt;
  expect(r.sha256).toBe(createHash('sha256').update(bytes).digest('hex'));expect(r.documentSha256).toBe(documentSha256(doc));expect(r.sizeBytes).toBe(bytes.length);
  expect(vault.resolve(issued.pdfReceiptToken,file,'synthetic',doc)).toEqual(r);
  for(const [token,f,slug,d] of [[issued.pdfReceiptToken,file,'other',doc],['wrong',file,'synthetic',doc],[issued.pdfReceiptToken,file+'x','synthetic',doc],[issued.pdfReceiptToken,file,'synthetic',{...doc,title:'changed'}]] as const)expect(()=>vault.resolve(token,f,slug,d)).toThrow();
 });
 it('detects same-length replacement, non-PDF, deletion and identical recovered bytes',async()=>{
  const {file,issued}=await fixture(),r=issued.pdfReceipt;
  expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('verified');
  const modified=Buffer.from(bytes);modified[12]=modified[12]!^1;await fs.writeFile(file,modified);
  expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('changed');
  await fs.writeFile(file,Buffer.alloc(bytes.length,65));expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('changed');
  await fs.rm(file);expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('missing');
  await fs.writeFile(file,bytes);expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('verified');
 });
 it('rejects hard links, directories, wrong extension and oversized files',async()=>{
  const {root,file,issued}=await fixture();const r=issued.pdfReceipt,link=path.join(root,'other.pdf');
  await fs.link(file,link);expect(checkFingerprint(await readPdfFingerprint(file),r).status).toBe('unsafe');await fs.rm(link);
  await fs.mkdir(link);expect(checkFingerprint(await readPdfFingerprint(link),r).status).toBe('unsafe');
  expect((await readPdfFingerprint(file+'.txt')).status).toBe('unsafe');
  await fs.truncate(file,MAX_RECEIPT_PDF_BYTES+1);expect((await readPdfFingerprint(file)).status).toBe('unavailable');
 });
 it('does not issue a receipt when actual file bytes differ or a token is expired',async()=>{
  const {file,doc}=await fixture();let time=Date.now();const v=new PdfReceiptVault(()=>time);
  const r=await v.issue(file,'synthetic',doc,bytes);time+=24*60*60*1000;
  expect(()=>v.resolve(r.pdfReceiptToken,file,'synthetic',doc)).toThrow();
  await fs.writeFile(file,'%PDF-1.7\nchanged');await expect(v.issue(file,'synthetic',doc,bytes)).rejects.toThrow();
 });
 it('does not authorize an arbitrary recorded path or a relative path',async()=>{
  const {root,dir,file}=await fixture();const outside=path.join(root,'outside.pdf');
  expect(canCheckRecordedPdf(file,dir,new Map())).toBe(true);
  expect(canCheckRecordedPdf(outside,dir,new Map())).toBe(false);
  expect(canCheckRecordedPdf(outside,dir,new Map([[outside,outside]]))).toBe(true);
  expect(canCheckRecordedPdf('outside.pdf',dir,new Map())).toBe(false);
 });
 it('allows a canonical directory alias but rejects a redirected managed child before hashing',async()=>{
  const {root,dir,file,issued}=await fixture(),alias=path.join(root,'managed-alias'),external=path.join(root,'external'),child=path.join(dir,'redirected');
  await fs.mkdir(external);await fs.writeFile(path.join(external,'resume.pdf'),bytes);
  await fs.symlink(dir,alias,process.platform==='win32'?'junction':'dir');
  await fs.symlink(external,child,process.platform==='win32'?'junction':'dir');
  try{
   const aliasFile=path.join(alias,'resume.pdf'),bad=path.join(child,'resume.pdf');
   expect(checkFingerprint(await readPdfFingerprint(aliasFile,undefined,real=>canCheckRecordedRealPdf(aliasFile,real,alias,new Map())),issued.pdfReceipt).status).toBe('verified');
   expect((await readPdfFingerprint(bad,undefined,real=>canCheckRecordedRealPdf(bad,real,dir,new Map()))).status).toBe('unsafe');
   expect((await readPdfFingerprint(file,undefined,async()=>false)).status).toBe('unsafe');
  }finally{await fs.unlink(alias).catch(()=>fs.rmdir(alias));await fs.unlink(child).catch(()=>fs.rmdir(child));}
 });
 it('respects an already-aborted read',async()=>{
  const {file}=await fixture();const ctl=new AbortController();ctl.abort();expect((await readPdfFingerprint(file,ctl.signal)).status).toBe('unavailable');
 });
});
describe('immutable receipt in ledger and permanent archive',()=>{
 it('stores identical receipt in both records, protects it on CAS saves and idempotent retry',async()=>{
  const {store,doc,entry,issued}=await fixture();const input={entry,document:doc,pdfReceiptToken:issued.pdfReceiptToken};
  const saved=await store.logApplication(input,issued.pdfReceipt);
  const link={applicationId:entry.id,snapshotId:saved.entry.snapshotId,ledgerRevision:saved.store.revision!};
  expect(saved.entry.pdfReceipt).toEqual(issued.pdfReceipt);expect((await store.getLinkedApplicationSnapshot(link)).meta.pdfReceipt).toEqual(issued.pdfReceipt);
  expect((await store.logApplication(input,issued.pdfReceipt)).store.applications).toHaveLength(1);
  for(const r of [undefined,{...issued.pdfReceipt,sha256:'0'.repeat(64)}]){
   await expect(store.saveApplications({...saved.store,applications:[{...saved.entry,pdfReceipt:r}]},saved.store.revision)).rejects.toMatchObject({code:'SNAPSHOT_LINK_PROTECTED'});
  }
  const next=await store.saveApplications({...saved.store,applications:[{...saved.entry,status:'interview'}]},saved.store.revision);
  expect(next.applications[0]?.pdfReceipt).toEqual(issued.pdfReceipt);
 });
 it('rejects renderer-supplied hash, untrusted token and document mismatch before writing',async()=>{
  const {store,doc,entry,issued}=await fixture();
  await expect(store.logApplication({entry:{...entry,pdfReceipt:issued.pdfReceipt},document:doc})).rejects.toMatchObject({code:'PDF_RECEIPT_UNTRUSTED'});
  await expect(store.logApplication({entry,document:doc,pdfReceiptToken:'forged'})).rejects.toMatchObject({code:'PDF_RECEIPT_UNTRUSTED'});
  await expect(store.logApplication({entry,document:{...doc,title:'changed'}},issued.pdfReceipt)).rejects.toMatchObject({code:'PDF_RECEIPT_MISMATCH'});
  expect((await store.getApplications()).applications).toEqual([]);
 });
 it('keeps historical records without a receipt readable, never backfills a hash',async()=>{
  const {store,doc,entry,issued}=await fixture();const saved=await store.logApplication({entry,document:doc});
  const rec=await store.getLinkedApplicationSnapshot({applicationId:entry.id,snapshotId:saved.entry.snapshotId,ledgerRevision:saved.store.revision!});
  expect(rec.meta.pdfReceipt).toBeUndefined();expect(saved.entry.pdfReceipt).toBeUndefined();
  await expect(store.saveApplications({...saved.store,applications:[{...saved.entry,pdfReceipt:issued.pdfReceipt}]},saved.store.revision)).rejects.toMatchObject({code:'SNAPSHOT_LINK_PROTECTED'});
 });
 it('refuses tampered archive receipt or document even if file still matches',async()=>{
  const {store,doc,entry,issued}=await fixture();const saved=await store.logApplication({entry,document:doc},issued.pdfReceipt);
  const file=path.join(store.appSnapshotsDir,saved.entry.snapshotId+'.json'),raw=JSON.parse(await fs.readFile(file,'utf8')),link={applicationId:entry.id,snapshotId:saved.entry.snapshotId,ledgerRevision:saved.store.revision!};
  for(const modified of [{...raw,meta:{...raw.meta,pdfReceipt:{...issued.pdfReceipt,sha256:'0'.repeat(64)}}},{...raw,document:{...raw.document,basic:{...raw.document.basic,name:'tampered'}}}]){
   await fs.writeFile(file,JSON.stringify(modified));await expect(store.getLinkedApplicationSnapshot(link)).rejects.toMatchObject({code:'APPLICATION_SNAPSHOT_LINK'});
  }
 });
});
