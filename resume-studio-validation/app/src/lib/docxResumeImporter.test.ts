function zip(items:Item[]):Uint8Array{
  const locals:Buffer[]=[],centrals:Buffer[]=[];let offset=0;
  for(const item of items){
    const raw=Buffer.from(item.text),name=Buffer.from(item.name),localName=Buffer.from(item.localName??item.name),data=item.store?raw:deflateRawSync(raw),method=item.store?0:8,flags=(item.flags??0)|(item.descriptor?8:0);
    const checksum=item.crc??crc(raw),size=item.declared??raw.length;
    const l=Buffer.alloc(30),c=Buffer.alloc(46);
    l.writeUInt32LE(0x04034b50);l.writeUInt16LE(20,4);l.writeUInt16LE(flags,6);l.writeUInt16LE(method,8);
    if(!item.descriptor){l.writeUInt32LE(checksum,14);l.writeUInt32LE(data.length,18);l.writeUInt32LE(size,22);}
    l.writeUInt16LE(localName.length,26);
    c.writeUInt32LE(0x02014b50);c.writeUInt16LE(20,4);c.writeUInt16LE(20,6);c.writeUInt16LE(flags,8);c.writeUInt16LE(method,10);c.writeUInt32LE(checksum,16);c.writeUInt32LE(data.length,20);c.writeUInt32LE(size,24);c.writeUInt16LE(name.length,28);c.writeUInt32LE(item.offsetOverride??offset,42);
    const desc=item.descriptor?Buffer.alloc(item.descriptor==='signed'?16:12):Buffer.alloc(0);
    if(item.descriptor){const i=item.descriptor==='signed'?4:0;if(i)desc.writeUInt32LE(0x08074b50);desc.writeUInt32LE(checksum,i);desc.writeUInt32LE(data.length,i+4);desc.writeUInt32LE(size,i+8);}
    const local=Buffer.concat([l,localName,data,desc]);locals.push(local);centrals.push(Buffer.concat([c,name]));offset+=local.length;
  }
  const cd=Buffer.concat(centrals),end=Buffer.alloc(22);end.writeUInt32LE(0x06054b50);end.writeUInt16LE(items.length,8);end.writeUInt16LE(items.length,10);end.writeUInt32LE(cd.length,12);end.writeUInt32LE(offset,16);return new Uint8Array(Buffer.concat([...locals,cd,end]));
}
